-- Renovación anual: la plataforma considera NO DISPONIBLE a quien lleva más de 1 año sin confirmar.
-- Esta función puede ejecutarse con un cron diario más adelante.
create or replace function public.expire_old_availability()
returns void language sql security definer set search_path=public as $$
  update public.profiles set is_available=false
  where is_available=true and coalesce(last_profile_confirmation,created_at) < now()-interval '1 year';
$$;


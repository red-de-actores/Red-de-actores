-- Blindaje: un actor NO puede auto-aprobarse, hacerse admin, destacarse, verificarse ni ocultarse.
create or replace function public.protect_moderation_fields()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if public.is_admin() then return new; end if;
  if auth.uid()=old.id then
    new.role := old.role;
    new.is_featured := old.is_featured;
    new.is_verified := old.is_verified;
    new.is_hidden := old.is_hidden;
    new.approved_at := old.approved_at;
    new.rejection_reason := old.rejection_reason;

    -- Primera presentación o reenvío tras rechazo: puede pasar a pending.
    -- Una vez aprobado, los cambios cotidianos quedan publicados sin nueva revisión.
    if old.status in ('draft','rejected') and new.status='pending' then
      null;
    else
      new.status := old.status;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists protect_profiles_moderation on public.profiles;
create trigger protect_profiles_moderation before update on public.profiles
for each row execute procedure public.protect_moderation_fields();

create or replace function public.set_profile_slug()
returns trigger language plpgsql set search_path=public as $$
begin
  if new.display_name is not null and (new.slug is null or new.slug='') then
    new.slug := trim(both '-' from regexp_replace(lower(translate(new.display_name,'áéíóúüñÁÉÍÓÚÜÑ','aeiouunAEIOUUN')),'[^a-z0-9]+','-','g')) || '-' || left(new.id::text,6);
  end if;
  return new;
end $$;

drop trigger if exists profiles_set_slug on public.profiles;
create trigger profiles_set_slug before insert or update of display_name on public.profiles
for each row execute procedure public.set_profile_slug();


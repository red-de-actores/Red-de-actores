create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'actor' check (role in ('actor','admin')),
  status text not null default 'draft' check (status in ('draft','pending','approved','rejected')),
  display_name text,
  slug text unique,
  birth_date date,
  city text,
  bio text default '',
  skills text[] not null default '{}',
  is_available boolean not null default false,
  accepts_student_work boolean not null default false,
  photo_url text,
  photo_url_2 text,
  photo_url_3 text,
  presentation_url text,
  reel_url text,
  monologue_url text,
  is_featured boolean not null default false,
  is_verified boolean not null default false,
  is_hidden boolean not null default false,
  rejection_reason text,
  submitted_at timestamptz,
  approved_at timestamptz,
  last_profile_confirmation timestamptz default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint max_seven_skills check (cardinality(skills) <= 7)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null,
  title text not null,
  body text,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id) values(new.id) on conflict do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

alter table public.profiles enable row level security;
alter table public.notifications enable row level security;

drop policy if exists "owner reads profile" on public.profiles;
create policy "owner reads profile" on public.profiles for select using (auth.uid()=id or public.is_admin());
drop policy if exists "owner updates profile" on public.profiles;
create policy "owner updates profile" on public.profiles for update using (auth.uid()=id or public.is_admin()) with check (auth.uid()=id or public.is_admin());

drop policy if exists "user reads notifications" on public.notifications;
create policy "user reads notifications" on public.notifications for select using (auth.uid()=user_id or public.is_admin());
drop policy if exists "user updates notifications" on public.notifications;
create policy "user updates notifications" on public.notifications for update using (auth.uid()=user_id or public.is_admin());

-- Los perfiles públicos salen SOLO por estas RPC: jamás devuelven birth_date.
create or replace function public.get_public_actors()
returns table(
  id uuid, slug text, display_name text, age_years int, city text, bio text, skills text[],
  is_available boolean, accepts_student_work boolean, photo_url text, photo_url_2 text, photo_url_3 text,
  presentation_url text, reel_url text, monologue_url text, is_featured boolean, is_verified boolean, updated_at timestamptz
)
language sql stable security definer set search_path=public as $$
  select p.id,p.slug,p.display_name,
    date_part('year',age(current_date,p.birth_date))::int,
    p.city,p.bio,p.skills,(p.is_available and coalesce(p.last_profile_confirmation,p.created_at) >= now()-interval '1 year') as is_available,p.accepts_student_work,p.photo_url,p.photo_url_2,p.photo_url_3,
    p.presentation_url,p.reel_url,p.monologue_url,p.is_featured,p.is_verified,p.updated_at
  from public.profiles p
  where p.status='approved' and p.is_hidden=false and p.display_name is not null
  order by p.is_featured desc,p.updated_at desc;
$$;

grant execute on function public.get_public_actors() to anon, authenticated;

create or replace function public.get_public_actor(actor_ref text)
returns table(

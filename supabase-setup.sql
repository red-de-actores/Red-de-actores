-- Notificaciones automáticas al aprobar/rechazar.
create or replace function public.notify_moderation()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if old.status is distinct from new.status and new.status='approved' then
    insert into public.notifications(user_id,type,title,body) values(new.id,'profile_approved','Perfil aprobado','Tu perfil ya está visible en Red de Actores.');
  elsif old.status is distinct from new.status and new.status='rejected' then
    insert into public.notifications(user_id,type,title,body) values(new.id,'profile_rejected','Tu perfil necesita correcciones',coalesce(new.rejection_reason,'Revisá tu perfil.'));
  end if;
  return new;
end $$;

drop trigger if exists profiles_moderation_notification on public.profiles;
create trigger profiles_moderation_notification after update on public.profiles for each row execute procedure public.notify_moderation();

